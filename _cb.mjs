import {createRequire} from 'module'; import {createServer} from 'http'; import {readFile} from 'fs/promises'; import {extname, join} from 'path';
const require = createRequire(import.meta.url); const {chromium} = require('playwright');
const T = {'.html': 'text/html', '.js': 'text/javascript'};
const s = createServer(async (q, r) => { let p = decodeURIComponent(new URL(q.url, 'http://x').pathname); try { const b = await readFile(join('/home/user/night-watch', p)); r.writeHead(200, {'content-type': T[extname(p)] || 'application/octet-stream'}); r.end(b); } catch(e){ r.writeHead(404); r.end(); } });
await new Promise(r => s.listen(0, r));
const b = await chromium.launch({args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader']});
const p = await b.newPage(); p.on('pageerror', e => console.log('ERR', e.message));
await p.setViewportSize({width: 1400, height: 500});
await p.goto(`http://localhost:${s.address().port}/tools/cowboys.html${process.argv[3] || ''}`);
const tt = Date.now(); while(!(await p.evaluate(() => window.ready)) && Date.now() - tt < 30000) await new Promise(r => setTimeout(r, 300));
await new Promise(r => setTimeout(r, +(process.argv[4] || 2500)));
console.log(await p.evaluate(() => JSON.stringify(window.BONES)));
await p.screenshot({path: process.argv[2]});
await b.close(); s.close();
